// Índice do dia (muda à meia-noite no horário do aparelho).
function dayIndex(date = new Date()) {
  const d = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate());
  return Math.floor(d / 86400000) % DAILY.length;
}
